#!/usr/bin/env python3
"""A2 Step 4 accuracy test: score every configuration's test-set run against the Step 1 limits.

    python analysis/a2_accuracy.py <run-id> [<run-id> ...]

Each run is one pass of the 88 test tickets through POST /tickets (tests/accuracy/accuracy_test.py with
--golden datasets/a2/test_set.csv). Limits come from analysis/output/a2_limits.json (run a2_limits.py first).
For each configuration: overall and per-category accuracy with counts, pass/fail against both limits,
confusion matrix (counts and % of the true category), most common mistakes, and for cascades the escalation
fraction from the service log plus accuracy of escalated vs non-escalated tickets.
Writes analysis/output/a2_accuracy.md, a2_accuracy.csv, a2_confusion.csv and one heatmap per configuration.
"""
import json
import sys
from collections import Counter, defaultdict

from a2common import (FIG_DIR, LIMITS_JSON, NO_ANSWER, confusion_rows, confusion_sections, file_slug, heatmap,
                      load_test_run, macro_accuracy, pct, predicted, read_test_set, reconcile_verdict, score, short)
from runlib import CATEGORIES, OUTPUT_DIR, md_table, write_csv

OUT_MD = OUTPUT_DIR / "a2_accuracy.md"
OUT_CSV = OUTPUT_DIR / "a2_accuracy.csv"
OUT_CONFUSION = OUTPUT_DIR / "a2_confusion.csv"


def check(s: dict, limits: dict) -> dict:
    overall_ok = s["correct"] >= limits["overall"]["min_correct"]
    cats = {c: s["per_category"][c]["correct"] >= limits["categories"][c]["min_correct"] for c in CATEGORIES}
    return {"overall": overall_ok, "categories": cats, "pass": overall_ok and all(cats.values())}


def escalation(run, s: dict) -> dict | None:
    """Escalation fraction from the service log, and whether the rule catches the small model's mistakes."""
    if not run.is_cascade:
        return None
    if len(run.route) != len(run.preds):
        sys.exit(f"{run.run_id}: only {len(run.route)}/{len(run.preds)} tickets found in server_access.log "
                 "(joined on req_id) - the escalation fraction cannot be taken from the logs")
    esc = {row for row, f in run.route.items() if str(f.get("escalated")) == "1"}
    kept = set(run.preds) - esc
    right = {row for row, p in run.preds.items() if predicted(p) == p["golden_label"]}
    small_right = {row for row, f in run.route.items()
                   if f.get("small_answer") == run.preds[row]["golden_label"]}
    final_models = Counter(f.get("final_model", "?") for f in run.route.values())
    return {
        "n": len(run.preds), "escalated": len(esc), "kept": len(kept),
        "escalated_correct": len(esc & right), "kept_correct": len(kept & right),
        "kept_wrong_let_through": len(kept - right),
        "escalated_small_was_right": len(esc & small_right),  # escalations the small model did not need
        "escalated_small_was_wrong": len(esc - small_right),  # small-model mistakes the rule caught
        "final_models": dict(final_models),
        "kept_wrong_by_pred": Counter(run.preds[r]["predicted"] for r in kept - right),
    }


def main():
    run_ids = sys.argv[1:]
    if not run_ids:
        sys.exit(__doc__)
    if not LIMITS_JSON.exists():
        sys.exit(f"{LIMITS_JSON} not found - run analysis/a2_limits.py on the top model's test-set run first")
    limits = json.loads(LIMITS_JSON.read_text(encoding="utf-8"))
    labels = read_test_set()

    results = []
    for run_id in run_ids:
        run = load_test_run(run_id, labels)
        s = score(run.preds)
        results.append((run, s, check(s, limits), escalation(run, s), reconcile_verdict(run)))
    if limits["source_run"] not in {r.run_id for r, *_ in results}:
        print(f"note: the reference run {limits['source_run']} is not in this report; limits still come from it")

    o = limits["overall"]
    lines = [
        "# A2 accuracy test: every configuration on the test set (generated)", "",
        f"Generated by `python analysis/a2_accuracy.py {' '.join(r.run_id for r, *_ in results)}`. "
        f"Test set: {limits['n']} tickets (even golden rows). Limits from `{limits['source_run']}` "
        f"({limits['model']}: {limits['top_correct']}/{limits['n']}, {limits['top_accuracy_pct']:.1f}%): overall "
        f"≥ {o['min_correct']}/{limits['n']} ({o['limit_pct']:.1f}%), each category ≥ its limit below. "
        "Only test-set results decide pass/fail.", "",
        "## Summary", "",
    ]
    summary, csv_rows, confusion_long = [], [], []
    for run, s, ok, esc, verdict in results:
        failed = [short(c) for c, good in ok["categories"].items() if not good]
        summary.append([run.label, f"{s['correct']}/{s['n']} ({pct(s['correct'], s['n'])})",
                        "pass" if ok["overall"] else "**FAIL**", "pass" if not failed else "**FAIL**: " + ", ".join(failed),
                        f"{100 * macro_accuracy(s):.1f}%",
                        f"{esc['escalated']}/{esc['n']} ({pct(esc['escalated'], esc['n'])})" if esc else "-",
                        "**PASS**" if ok["pass"] else "FAIL", verdict])
        row = {"config": run.label, "run_id": run.run_id, "model": run.model, "cascade": run.cascade,
               "large_model": run.large_model or "", "n": s["n"], "correct": s["correct"],
               "accuracy_pct": 100 * s["accuracy"], "no_answer": s["no_answer"],
               "macro_accuracy_pct": 100 * macro_accuracy(s), "overall_pass": ok["overall"],
               "categories_pass": all(ok["categories"].values()), "pass": ok["pass"], "reconciliation": verdict}
        for c in CATEGORIES:
            pc = s["per_category"][c]
            row[f"correct_{c}"], row[f"n_{c}"], row[f"pass_{c}"] = pc["correct"], pc["n"], ok["categories"][c]
        if esc:
            row.update({k: v for k, v in esc.items() if not isinstance(v, (dict, Counter))})
            row["escalation_fraction"] = esc["escalated"] / esc["n"]
        csv_rows.append(row)
        confusion_long += confusion_rows(run.label, run.run_id, s["matrix"])
    lines += [md_table(["Configuration", "Overall", "Overall limit", "Per-category limits", "Balanced acc.",
                        "Escalated", "Verdict", "Reconciliation"], summary), "",
              "Balanced accuracy (mean of per-category accuracy) is shown because the test set is imbalanced "
              "(4–20 tickets per category); it is context only and does not decide pass/fail.", ""]

    # Per-category table: one column per configuration, with the limit.
    head = ["Category", "n", "Limit"] + [r.label for r, *_ in results]
    rows = []
    for c in CATEGORIES:
        L = limits["categories"][c]
        cells = []
        for run, s, ok, *_ in results:
            pc = s["per_category"][c]
            mark = "" if ok["categories"][c] else " ✗"
            cells.append(f"{pc['correct']}/{pc['n']} ({pct(pc['correct'], pc['n'])}){mark}")
        rows.append([c + (" ⚠" if L["small"] else ""), L["n"], f"≥ {L['min_correct']} ({L['limit_pct']:.1f}%)"]
                    + cells)
    lines += ["## Per category (right/n; ✗ = below the limit)", "",
              "⚠ = fewer than 10 test tickets: one ticket moves the figure by more than 10 points, so the limit is "
              "a coarse test there.", "", md_table(head, rows), ""]

    # Cross-configuration view of mistakes.
    pairs = defaultdict(dict)
    for run, s, *_ in results:
        for (g, p), v in s["matrix"].items():
            if g != p and v:
                pairs[(g, p)][run.label] = v
    ranked = sorted(pairs.items(), key=lambda kv: (-sum(kv[1].values()), kv[0]))
    lines += ["## Mistakes across configurations (true -> predicted, ticket counts)", "",
              "Which errors are shared by every model (likely ambiguous tickets or label boundaries) and which "
              "are specific to one model.", "",
              md_table(["True", "Predicted as", "Total"] + [r.label for r, *_ in results],
                       [[g, p, sum(v.values())] + [v.get(r.label, "·") for r, *_ in results]
                        for (g, p), v in ranked[:15]]), ""]

    # Per-configuration detail.
    for run, s, ok, esc, verdict in results:
        fig = FIG_DIR / f"a2_confusion_{file_slug(run.label)}.png"
        heatmap(run.label, s, fig)
        lines += [f"## {run.label}", "",
                  f"Run `runs/{run.run_id}/`. {s['correct']}/{s['n']} correct ({pct(s['correct'], s['n'])}), "
                  f"{s['n'] - s['correct']} wrong, {s['no_answer']} with no answer. Reconciliation: {verdict}. "
                  f"Heatmap: `{fig.relative_to(OUTPUT_DIR.parent.parent).as_posix()}`.", ""]
        if esc:
            lines += [
                "### Escalation (from server_access.log, joined to the answers on req_id)", "",
                md_table(["", "Tickets", "Correct", "Accuracy"], [
                    ["Escalated (large model answered)", esc["escalated"], esc["escalated_correct"],
                     pct(esc["escalated_correct"], esc["escalated"])],
                    ["Not escalated (small model's answer kept)", esc["kept"], esc["kept_correct"],
                     pct(esc["kept_correct"], esc["kept"])],
                    ["All", esc["n"], s["correct"], pct(s["correct"], s["n"])]]), "",
                f"- Escalation fraction: **{esc['escalated']}/{esc['n']} ({pct(esc['escalated'], esc['n'])})**. "
                f"Final answers by model: " + ", ".join(f"{m} {k}" for m, k in esc["final_models"].items()) + ".",
                f"- Small-model mistakes caught by the rule (escalated, small answer wrong): "
                f"{esc['escalated_small_was_wrong']}; escalations the small model did not need (its answer was "
                f"already right): {esc['escalated_small_was_right']}.",
                f"- Wrong answers let through (not escalated and wrong): **{esc['kept_wrong_let_through']}**"
                + (" — kept because the small model predicted: " + ", ".join(
                    f"{short(p)} {k}" for p, k in esc["kept_wrong_by_pred"].most_common()) if
                   esc["kept_wrong_let_through"] else "") + ".", ""]
        lines += confusion_sections(s)

    write_csv(OUT_CSV, csv_rows)
    write_csv(OUT_CONFUSION, confusion_long)
    OUT_MD.write_text("\n".join(lines), encoding="utf-8")
    print("\n".join(lines))
    print(f"\nWrote {OUT_MD}, {OUT_CSV}, {OUT_CONFUSION} and heatmaps in {FIG_DIR}")


if __name__ == "__main__":
    main()
