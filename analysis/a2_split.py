#!/usr/bin/env python3
"""A2 Step 1: split the frozen golden set by row number, odd rows = tuning set, even rows = test set."""
import csv
import hashlib
import io
from collections import Counter
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
GOLDEN = REPO_ROOT / "datasets" / "golden_test_set.csv"
OUT_DIR = REPO_ROOT / "datasets" / "a2"
LABEL = "final_agreed_label"
SMALL = 10  # fewer test tickets than this in a category: one ticket moves its accuracy by more than 10 points


def read_golden(path: Path) -> list[dict]:
    """Same reader as tests/accuracy/accuracy_test.py: the frozen file is Windows-1252 (saved from Excel)."""
    raw = path.read_bytes()
    try:
        text = raw.decode("utf-8-sig")
    except UnicodeDecodeError:
        text = raw.decode("cp1252")
    return list(csv.DictReader(io.StringIO(text, newline="")))


def write_split(path: Path, fields: list[str], rows: list[dict]):
    with open(path, "w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=fields)
        writer.writeheader()
        writer.writerows(rows)


def main():
    golden = sorted(read_golden(GOLDEN), key=lambda r: int(r["row"]))
    fields = list(golden[0])
    tuning = [r for r in golden if int(r["row"]) % 2 == 1]
    test = [r for r in golden if int(r["row"]) % 2 == 0]
    assert len(tuning) + len(test) == len(golden) and len({r["row"] for r in golden}) == len(golden)

    OUT_DIR.mkdir(exist_ok=True)
    write_split(OUT_DIR / "tuning_set.csv", fields, tuning)
    write_split(OUT_DIR / "test_set.csv", fields, test)

    counts = {name: Counter(r[LABEL].strip() for r in rows) for name, rows in (("golden", golden),
                                                                              ("tuning", tuning), ("test", test))}
    lines = [
        "# A2 golden-set split (generated)",
        "",
        f"Generated by `python analysis/a2_split.py` from `datasets/golden_test_set.csv` "
        f"(sha256 `{hashlib.sha256(GOLDEN.read_bytes()).hexdigest()}`, {len(golden)} tickets, unchanged).",
        "",
        "Rule (A2 brief, Step 1): sort by the `row` column (the dataset row number); odd row numbers are the "
        "**tuning set**, even row numbers are the **test set**. The tuning set is for designing the escalation "
        "rule and choosing its two settings; every reported accuracy number and the limits come from the test set.",
        "",
        f"- `tuning_set.csv`: {len(tuning)} tickets (odd rows)",
        f"- `test_set.csv`: {len(test)} tickets (even rows)",
        "",
        "Both files keep the golden set's columns and labels (`final_agreed_label`), so they can be passed to "
        "`tests/accuracy/accuracy_test.py --golden datasets/a2/test_set.csv`.",
        "",
        "| Category | Golden | Tuning | Test | Test-set note |",
        "|---|---|---|---|---|",
    ]
    for category in sorted(counts["golden"], key=lambda c: -counts["golden"][c]):
        n = counts["test"][category]
        note = f"small: 1 ticket = {100 / n:.1f} points" if n < SMALL else f"1 ticket = {100 / n:.1f} points"
        lines.append(f"| {category} | {counts['golden'][category]} | {counts['tuning'][category]} | {n} | {note} |")
    lines.append(f"| **Total** | {len(golden)} | {len(tuning)} | {len(test)} | |")
    (OUT_DIR / "split_summary.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
