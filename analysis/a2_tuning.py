#!/usr/bin/env python3
"""A2 Step 2: choose the category-based cascade's accept lists from phi3's answers on the TUNING set only.

The test set is never read. Small-model answers are the A1 phi3:3.8b runs 4-6 and large-model answers the A1
gemma4:e4b runs 1, 3 and 4 (thinking on, as in A1), both from analysis/output/accuracy_predictions.csv and
restricted to tuning rows. Cascade estimates assume escalated tickets get gemma4's answer, as the cascade would.
"""
import csv
from collections import Counter, defaultdict
from pathlib import Path

from runlib import load_exclusions, load_runs, read_mysql_tsv

REPO_ROOT = Path(__file__).resolve().parent.parent
TUNING = REPO_ROOT / "datasets" / "a2" / "tuning_set.csv"
PREDICTIONS = REPO_ROOT / "analysis" / "output" / "accuracy_predictions.csv"
OUT = REPO_ROOT / "analysis" / "output" / "a2_tuning.md"
SMALL_RUNS = [f"phi3-3.8b_accuracy_golden175_run{n}" for n in (4, 5, 6)]
LARGE_RUNS = [f"gemma4-e4b_accuracy_golden175_run{n}" for n in (1, 3, 4)]
# Rough single-ticket latencies on the SUT (s): phi3 median of the A2 memory check (tests/environment/a2_memcheck),
# gemma4 the A1 P5 baseline. The A2 speed tests replace both.
SMALL_S, LARGE_S = 2.1, 33.5


def pct(a, b):
    return f"{100 * a / b:.1f}%" if b else "-"


def table(headers, rows):
    return ["| " + " | ".join(headers) + " |", "|" + "---|" * len(headers)] + \
           ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]


def sut_crosscheck(narratives: dict, preds: dict) -> list[list]:
    """Tuning tickets that A1 load/stress runs also sent to the official SUT: same answer there as in the A1 runs?"""
    def norm(text):
        return " ".join(text.split())[:200]

    row_by_text = {norm(text): row for row, text in narratives.items()}
    excluded = load_exclusions()
    seen = defaultdict(lambda: defaultdict(Counter))  # model -> tuning row -> SUT categories
    runs_used = defaultdict(set)
    for run in load_runs({"load", "stress"}):
        if run.run_id in excluded or not (run.path / "tickets.tsv").exists():
            continue
        for t in read_mysql_tsv(run.path / "tickets.tsv"):
            row = row_by_text.get(norm(t.get("narrative", "")))
            if row and t.get("category"):
                seen[run.info["model"]][row][t["category"]] += 1
                runs_used[run.info["model"]].add(run.run_id)
    out = []
    for model, runs in (("phi3:3.8b", SMALL_RUNS), ("gemma4:e4b", LARGE_RUNS)):
        rows_seen = seen[model]
        same = sum(set(cats) == {preds[row][k] for k in runs} for row, cats in rows_seen.items())
        out.append([model, len(rows_seen), sum(sum(c.values()) for c in rows_seen.values()),
                    len(runs_used[model]), f"{same}/{len(rows_seen)}"])
    return out


def main():
    tuning_rows = list(csv.DictReader(open(TUNING, encoding="utf-8")))
    tuning = {r["row"]: r["final_agreed_label"].strip() for r in tuning_rows}
    preds = {r["row"]: r for r in csv.DictReader(open(PREDICTIONS, encoding="utf-8")) if r["row"] in tuning}
    assert set(preds) == set(tuning), "every tuning row needs A1 answers"
    rows = sorted(tuning, key=int)

    small, unstable = {}, 0
    for row in rows:
        answers = [preds[row][k] for k in SMALL_RUNS]
        unstable += len(set(answers)) > 1
        small[row] = Counter(answers).most_common(1)[0][0]
    large_ok = {row: sum(preds[row][k] == tuning[row] for k in LARGE_RUNS) / len(LARGE_RUNS) for row in rows}
    categories = sorted(set(tuning.values()), key=lambda c: -sum(v == c for v in tuning.values()))
    n = len(rows)

    by_pred = defaultdict(list)
    for row in rows:
        by_pred[small[row]].append(row)
    precision = {c: sum(tuning[r] == c for r in by_pred[c]) / len(by_pred[c]) if by_pred[c] else 0 for c in categories}
    order = sorted(categories, key=lambda c: (-precision[c], -len(by_pred[c])))

    lines = ["# A2 cascade tuning analysis (generated)", "",
             f"Generated by `python analysis/a2_tuning.py`. Tuning set only ({n} tickets, odd rows); the test set "
             f"is not read. phi3 answers: A1 runs 4-6 ({unstable} tickets differ between runs; majority used). "
             "gemma4 answers: A1 runs 1, 3, 4 (thinking on), scored as the share of runs correct.", "",
             "## phi3 by PREDICTED category (what the rule can see)", ""]
    pred_rows = []
    for c in order:
        wrong = Counter(tuning[r] for r in by_pred[c] if tuning[r] != c)
        right = len(by_pred[c]) - sum(wrong.values())
        pred_rows.append([c, len(by_pred[c]), right, pct(right, len(by_pred[c])),
                          ", ".join(f"{t} {k}" for t, k in wrong.most_common()) or "-"])
    lines += table(["phi3 predicted", "Tickets", "Correct", "Precision", "Wrong ones are really"], pred_rows)

    lines += ["", "## Per TRUE category: phi3, gemma4 and proxy floors (tuning set)", "",
              "Proxy limits use gemma4 on the tuning set (overall -10, category -15). The real limits come from the "
              "test-set run of gemma4; these only show whether a setting is in range.", ""]
    large_cat = {c: sum(large_ok[r] for r in rows if tuning[r] == c) for c in categories}
    true_rows = []
    for c in categories:
        k = sum(tuning[r] == c for r in rows)
        s = sum(small[r] == c for r in rows if tuning[r] == c)
        true_rows.append([c, k, f"{s}/{k} ({pct(s, k)})", f"{large_cat[c]:.1f}/{k} ({pct(large_cat[c], k)})",
                          f"{100 * large_cat[c] / k - 15:.1f}%"])
    large_total = sum(large_ok.values())
    lines += table(["True category", "n", "phi3", "gemma4 (mean)", "Proxy floor"], true_rows)
    lines += ["", f"gemma4 overall on tuning: {large_total:.1f}/{n} ({pct(large_total, n)}); "
              f"proxy overall limit {100 * large_total / n - 10:.1f}%. "
              f"phi3 alone: {sum(small[r] == tuning[r] for r in rows)}/{n} "
              f"({pct(sum(small[r] == tuning[r] for r in rows), n)}).", ""]

    lines += ["## Candidate accept lists (accept phi3 when it predicts one of these; escalate the rest)", "",
              f"Categories added in order of tuning precision. Latency estimate = {SMALL_S} s + escalated share x "
              f"{LARGE_S} s (SUT figures, rough).", ""]
    cand_rows = []
    for k in range(len(order) + 1):
        accept = set(order[:k])
        esc = [r for r in rows if small[r] not in accept]
        acc = [r for r in rows if small[r] in accept]
        slipped = sum(tuning[r] != small[r] for r in acc)
        correct = sum(tuning[r] == small[r] for r in acc) + sum(large_ok[r] for r in esc)
        fails = []
        for c in categories:
            cat_rows = [r for r in rows if tuning[r] == c]
            got = sum((small[r] == c) if small[r] in accept else large_ok[r] for r in cat_rows)
            if 100 * got / len(cat_rows) < 100 * large_cat[c] / len(cat_rows) - 15:
                fails.append(f"{c} {got:.1f}/{len(cat_rows)}")
        overall_ok = 100 * correct / n >= 100 * large_total / n - 10
        cand_rows.append([k, ", ".join(order[:k]) or "(none: gemma4 for all)", f"{len(esc)}/{n} ({pct(len(esc), n)})",
                          slipped, f"{correct:.1f}/{n} ({pct(correct, n)})",
                          "yes" if overall_ok else "NO", "; ".join(fails) or "none",
                          f"{SMALL_S + len(esc) / n * LARGE_S:.1f} s" if k else f"{LARGE_S:.1f} s (gemma4 alone)"])
    lines += table(["k", "Accept phi3 when it predicts", "Escalated", "Wrong answers let through",
                    "Est. accuracy", "Overall proxy ok", "Categories below proxy floor", "Est. mean latency"],
                   cand_rows)

    lines += ["", "## Do the A1 answers above match the official SUT? (tuning tickets only)", "",
              "The A1 accuracy runs were on P3's machines. Tuning tickets that A1 load and stress runs also sent to "
              "the official SUT (`runs/<run-id>/tickets.tsv`, excluded runs skipped) are compared with the A1 "
              "accuracy-run answers for the same ticket. Same = the SUT's categories equal the accuracy runs' set.", ""]
    lines += table(["Model", "Tuning tickets seen on the SUT", "SUT answers", "SUT runs", "Same category"],
                   sut_crosscheck({r["row"]: r["narrative"] for r in tuning_rows}, preds))
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
