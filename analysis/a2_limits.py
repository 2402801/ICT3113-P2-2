#!/usr/bin/env python3
"""A2 Step 1: the client's accuracy limits, from the top A1 model's run on the TEST set (even golden rows).

    python analysis/a2_limits.py [run-id]      (default: gemma4-e4b_accuracy_a2test88_run1)

Overall limit      = top model's test-set accuracy - 10 percentage points.
Per-category limit = top model's test-set accuracy on that category - 15 percentage points
                     (the top model's own per-category figure, as the brief defines it, not the best of any model).
Each limit is also given as the minimum number of correct tickets, computed exactly (fractions, no rounding), so
later configurations are checked on counts. Writes analysis/output/a2_limits.md, a2_limits.json and a heatmap.
"""
import csv
import json
import math
import sys
from fractions import Fraction

from a2common import (FIG_DIR, LIMITS_JSON, SMALL_N, TEST_SET, confusion_sections, file_slug, heatmap,
                      load_test_run, macro_accuracy, pct, read_test_set, reconcile_verdict, score, sha256)
from runlib import CATEGORIES, OUTPUT_DIR, md_table

TOP_MODEL = "gemma4:e4b"
DEFAULT_RUN = "gemma4-e4b_accuracy_a2test88_run1"
OVERALL_DROP, CATEGORY_DROP = Fraction(10, 100), Fraction(15, 100)
A1_RUNS = [f"gemma4-e4b_accuracy_golden175_run{n}" for n in (1, 3, 4)]  # A1 runs kept in the A1 report
OUT_MD = OUTPUT_DIR / "a2_limits.md"


def min_correct(top_correct: int, n: int, drop: Fraction) -> int:
    """Smallest k with k/n >= top_correct/n - drop, i.e. k >= top_correct - drop*n (exact)."""
    return max(0, math.ceil(top_correct - drop * n))


def a1_comparison(test_rows: set[str]) -> list[list]:
    """The A1 gemma4 runs' answers on the same test rows (run-to-run spread, for context only)."""
    path = OUTPUT_DIR / "accuracy_predictions.csv"
    if not path.exists():
        return []
    with open(path, newline="", encoding="utf-8-sig") as f:
        rows = [r for r in csv.DictReader(f) if r["row"] in test_rows]
    out = []
    for run in A1_RUNS:
        if rows and run in rows[0]:
            k = sum(r[run] == r["golden_label"] for r in rows)
            out.append([run, f"{k}/{len(rows)}", pct(k, len(rows))])
    return out


def main():
    run_id = sys.argv[1] if len(sys.argv) > 1 else DEFAULT_RUN
    labels = read_test_set()
    run = load_test_run(run_id, labels)
    if run.model != TOP_MODEL or run.is_cascade:
        sys.exit(f"{run.run_id} was answered by {run.label}; the limits must come from {TOP_MODEL} alone")

    s = score(run.preds)
    n, top = s["n"], s["correct"]
    verdict = reconcile_verdict(run)
    overall_limit = Fraction(top, n) - OVERALL_DROP
    limits = {
        "source_run": run.run_id, "model": run.model, "test_set": TEST_SET.relative_to(TEST_SET.parents[2]).as_posix(),
        "test_set_sha256": sha256(TEST_SET), "reconciliation": verdict,
        "n": n, "top_correct": top, "top_accuracy_pct": round(100 * top / n, 3), "no_answer": s["no_answer"],
        "overall": {"drop_pp": 10, "limit_pct": round(float(100 * overall_limit), 3),
                    "min_correct": min_correct(top, n, OVERALL_DROP)},
        "categories": {},
    }
    for c in CATEGORIES:
        pc = s["per_category"][c]
        cn, ck = pc["n"], pc["correct"]
        limits["categories"][c] = {
            "n": cn, "top_correct": ck, "top_accuracy_pct": round(100 * ck / cn, 3),
            "drop_pp": 15, "limit_pct": round(float(100 * (Fraction(ck, cn) - CATEGORY_DROP)), 3),
            "min_correct": min_correct(ck, cn, CATEGORY_DROP), "pp_per_ticket": round(100 / cn, 1),
            "small": cn < SMALL_N,
        }
    LIMITS_JSON.write_text(json.dumps(limits, indent=2) + "\n", encoding="utf-8")

    fig = FIG_DIR / f"a2_confusion_{file_slug(run.model)}_limits.png"
    heatmap(run.model, s, fig)

    o = limits["overall"]
    lines = [
        "# A2 Step 1: accuracy limits (generated)", "",
        f"Generated by `python analysis/a2_limits.py {run.run_id}`. Source: `runs/{run.run_id}/` "
        f"({run.model} alone, cascade off), on `{limits['test_set']}` (even golden rows, sha256 "
        f"`{limits['test_set_sha256'][:16]}…`). Reconciliation: **{verdict}**. "
        f"Tickets with no answer (counted wrong): {s['no_answer']}.", "",
        "## Overall limit", "",
        f"- {run.model} on the test set: **{top}/{n} correct ({pct(top, n)})**, {n - top} wrong.",
        f"- Overall limit = {pct(top, n)} − 10 pp = **{o['limit_pct']:.1f}%**, i.e. a configuration needs "
        f"**at least {o['min_correct']}/{n} correct**.",
        f"- For context (not a limit): balanced accuracy (mean of per-category accuracy) "
        f"{100 * macro_accuracy(s):.1f}%.", "",
        "## Per-category limits", "",
        f"Limit = {run.model}'s accuracy on that category − 15 pp. ⚠ marks categories with fewer than {SMALL_N} "
        "test tickets: there one ticket is worth more than 10 points, so the per-category limit is a coarse test "
        "and a single unlucky ticket can decide pass or fail.", "",
    ]
    rows = []
    for c in CATEGORIES:
        L = limits["categories"][c]
        rows.append([c + (" ⚠" if L["small"] else ""), L["n"], f"{L['top_correct']}/{L['n']} right, "
                     f"{L['n'] - L['top_correct']} wrong", f"{L['top_accuracy_pct']:.1f}%",
                     f"{L['limit_pct']:.1f}%", f"≥ {L['min_correct']}/{L['n']}", f"{L['pp_per_ticket']:.1f} pp"])
    lines += [md_table(["Category", "Test tickets", f"{run.model}", "Accuracy", "Limit", "Needed to pass",
                        "1 ticket ="], rows), ""]
    lines += [f"## {run.model} on the test set", ""] + confusion_sections(s) + [
        f"Heatmap: `{fig.relative_to(OUTPUT_DIR.parent.parent).as_posix()}`.", ""]

    a1 = a1_comparison(set(labels))
    if a1:
        lines += ["## Context: A1 runs of the same model on the same test rows", "",
                  "Not used for the limits. Shows how much the top model varies between runs on identical tickets "
                  "(same digest, prompt and thinking setting), which is the noise floor for comparing "
                  "configurations on 88 tickets.", "",
                  md_table(["A1 run", "Correct", "Accuracy"], a1 + [[f"**A2 {run.run_id}**", f"{top}/{n}",
                                                                     pct(top, n)]]), ""]
    OUT_MD.write_text("\n".join(lines), encoding="utf-8")
    print("\n".join(lines))
    print(f"\nWrote {OUT_MD}, {LIMITS_JSON} and {fig}")


if __name__ == "__main__":
    main()
